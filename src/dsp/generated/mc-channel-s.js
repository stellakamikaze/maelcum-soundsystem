function peek(m, i) { return m[i]; }
function poke(m, v, i) { m[i] = v; }
function bq(m, i, x, b0, b1, b2, a1, a2) {
	let y = 0;
	y = b0 * x + peek(m, i);
	poke(m, b1 * x - a1 * y + peek(m, i + 1), i);
	poke(m, b2 * x - a2 * y, i + 1);
	return y;
}
function ap(m, i, x, c) {
	let y = 0;
	y = c * (x - peek(m, i + 1)) + peek(m, i);
	poke(m, x, i);
	poke(m, y, i + 1);
	return y;
}
